"""Stage E4: is the per-state optimum PREDICTABLE from what a policy can see?

Stages E2b and E3 established that choosing an overtime rung per state beats
the best constant (+0.64%) and that the per-state optimum replicates across
disjoint CRN seed families (agreement 0.93-1.00). Neither establishes the
property a learned policy actually needs: that the optimum can be predicted
from features observable at decision time.

Both prior results are compatible with a channel whose optimum is stable but
driven by realized future demand. Such a target is a perfectly reproducible
label and completely unlearnable, because the information is not in the state.
Stage E4 separates those cases, and it is the last gate before any actor may
be trained.

Design, mirroring the routing channel's Stage G1:

- Leave-one-state-seed-out. Fit on the states generated by all but one seed,
  predict on the held-out seed's states. Folds are grouped by GENERATION SEED,
  not by row, so no state contributes to both fitting and evaluation.
- The comparator is the STATE-BLIND predictor: always name the globally best
  constant rung. That is the honest baseline, because a model that cannot beat
  it has learned nothing about the state -- the same logic that made
  best-constant the reference in the E2 gate amendment.
- Reported per fold, never pooled only: G1 failed on per-seed floors while its
  pooled numbers looked tolerable.

The regressor is deliberately simple (ridge on standardized features, one
model per rung). A weak model that succeeds proves the signal is in the state;
a weak model that fails is not conclusive on its own, which is why the gate
also reports how much headroom the model leaves against the in-sample oracle.
"""

from __future__ import annotations

from collections import defaultdict
from itertools import combinations
from typing import Any, Iterable, Mapping, Sequence

import numpy as np

ANCHOR_ARM = "anchor"


def ridge_fit(features: np.ndarray, targets: np.ndarray, alpha: float) -> np.ndarray:
    """Closed-form ridge with an unpenalized intercept column."""

    design = np.hstack([features, np.ones((features.shape[0], 1))])
    penalty = alpha * np.eye(design.shape[1])
    penalty[-1, -1] = 0.0
    return np.linalg.solve(design.T @ design + penalty, design.T @ targets)


def ridge_predict(coefficients: np.ndarray, features: np.ndarray) -> np.ndarray:
    design = np.hstack([features, np.ones((features.shape[0], 1))])
    return design @ coefficients


def standardize(train: np.ndarray, apply_to: Sequence[np.ndarray]) -> list[np.ndarray]:
    mean = train.mean(axis=0)
    scale = train.std(axis=0)
    scale[scale < 1e-12] = 1.0
    return [(matrix - mean) / scale for matrix in apply_to]


def leave_one_seed_out_ranking(
    state_features: Mapping[str, np.ndarray],
    state_seed: Mapping[str, int],
    outcomes: Mapping[tuple[str, str], float],
    *,
    alpha: float = 1.0,
) -> dict[str, Any]:
    """Fit per-rung cost models on all but one generation seed; rank the rest.

    ``outcomes`` maps (state_id, arm) to the mean cost used as the label and as
    ground truth. Lower cost is better.
    """

    states = sorted(state_features)
    ladder = sorted({arm for _, arm in outcomes if arm != ANCHOR_ARM})
    if len(ladder) < 2:
        raise ValueError("at least two non-anchor arms are required")
    seeds = sorted({state_seed[state] for state in states})
    if len(seeds) < 2:
        raise ValueError("at least two generation seeds are required for folds")

    truth = {
        state: min(ladder, key=lambda arm: outcomes[(state, arm)]) for state in states
    }
    # State-blind comparator: the globally best constant rung.
    constant_totals = {
        arm: sum(outcomes[(state, arm)] for state in states) for arm in ladder
    }
    state_blind_arm = min(constant_totals, key=constant_totals.get)

    folds: list[dict[str, Any]] = []
    for held_out in seeds:
        train_states = [s for s in states if state_seed[s] != held_out]
        test_states = [s for s in states if state_seed[s] == held_out]
        if not train_states or not test_states:
            continue
        train_x = np.vstack([state_features[s] for s in train_states])
        test_x = np.vstack([state_features[s] for s in test_states])
        train_z, test_z = standardize(train_x, [train_x, test_x])

        predictions = np.zeros((len(test_states), len(ladder)))
        for index, arm in enumerate(ladder):
            targets = np.array([outcomes[(s, arm)] for s in train_states])
            centre = targets.mean()
            coefficients = ridge_fit(train_z, targets - centre, alpha)
            predictions[:, index] = ridge_predict(coefficients, test_z) + centre

        top1 = 0
        blind_top1 = 0
        pair_total = 0
        pair_agree = 0
        for row, state in enumerate(test_states):
            predicted_arm = ladder[int(np.argmin(predictions[row]))]
            if predicted_arm == truth[state]:
                top1 += 1
            if state_blind_arm == truth[state]:
                blind_top1 += 1
            for left, right in combinations(range(len(ladder)), 2):
                actual = outcomes[(state, ladder[left])] - outcomes[(state, ladder[right])]
                if actual == 0.0:
                    continue
                pair_total += 1
                predicted = predictions[row, left] - predictions[row, right]
                if (predicted > 0) == (actual > 0):
                    pair_agree += 1

        folds.append(
            {
                "held_out_seed": held_out,
                "states": len(test_states),
                "fitted_top1": top1 / len(test_states),
                "state_blind_top1": blind_top1 / len(test_states),
                "gain_over_state_blind": (top1 - blind_top1) / len(test_states),
                "pairwise_accuracy": (pair_agree / pair_total) if pair_total else 0.0,
            }
        )

    total_states = sum(fold["states"] for fold in folds)
    return {
        "state_count": len(states),
        "ladder_size": len(ladder),
        "chance_top1": 1.0 / len(ladder),
        "state_blind_arm": state_blind_arm,
        "folds": folds,
        "pooled_fitted_top1": sum(
            fold["fitted_top1"] * fold["states"] for fold in folds
        )
        / total_states,
        "pooled_state_blind_top1": sum(
            fold["state_blind_top1"] * fold["states"] for fold in folds
        )
        / total_states,
        "pooled_pairwise_accuracy": sum(
            fold["pairwise_accuracy"] * fold["states"] for fold in folds
        )
        / total_states,
        "worst_fold_top1": min(fold["fitted_top1"] for fold in folds),
        "worst_fold_gain": min(fold["gain_over_state_blind"] for fold in folds),
    }


def ranking_gate(
    report: Mapping[str, Any],
    *,
    minimum_top1: float,
    minimum_pairwise: float,
    minimum_gain_over_state_blind: float,
) -> dict[str, Any]:
    """Apply the prospective E4 criteria, including per-fold floors.

    Per-fold floors matter: Stage G1's pooled figures were less damning than
    its per-seed ones, and a channel that only works on two of three seeds is
    not a basis for training.
    """

    for name, value in (
        ("minimum_top1", minimum_top1),
        ("minimum_pairwise", minimum_pairwise),
    ):
        if not 0.0 < value <= 1.0:
            raise ValueError(f"{name} must be within (0, 1]")
    if minimum_gain_over_state_blind < 0.0:
        raise ValueError("minimum_gain_over_state_blind must be nonnegative")

    top1_ok = report["pooled_fitted_top1"] >= minimum_top1
    pairwise_ok = report["pooled_pairwise_accuracy"] >= minimum_pairwise
    per_fold_top1_ok = report["worst_fold_top1"] >= minimum_top1
    gain_ok = report["worst_fold_gain"] >= minimum_gain_over_state_blind
    passed = bool(top1_ok and pairwise_ok and per_fold_top1_ok and gain_ok)
    return {
        "gate": "e4_ranking_feasibility",
        "minimum_top1": minimum_top1,
        "minimum_pairwise": minimum_pairwise,
        "minimum_gain_over_state_blind": minimum_gain_over_state_blind,
        "measured_pooled_top1": report["pooled_fitted_top1"],
        "measured_pooled_pairwise": report["pooled_pairwise_accuracy"],
        "measured_worst_fold_top1": report["worst_fold_top1"],
        "measured_worst_fold_gain": report["worst_fold_gain"],
        "state_blind_top1": report["pooled_state_blind_top1"],
        "chance_top1": report["chance_top1"],
        "pooled_top1_passed": bool(top1_ok),
        "pairwise_passed": bool(pairwise_ok),
        "per_fold_top1_passed": bool(per_fold_top1_ok),
        "gain_over_state_blind_passed": bool(gain_ok),
        "ranking_gate_passed": passed,
        "classification": (
            "optimum_predictable_from_state"
            if passed
            else "optimum_not_predictable_from_state"
        ),
        "e5_design_authorized": passed,
    }
